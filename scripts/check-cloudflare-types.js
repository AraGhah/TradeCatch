#!/usr/bin/env node
/**
 * Are the committed Cloudflare binding types (worker-configuration.d.ts) current?
 *
 * `wrangler types --check` fails in two different situations:
 *   1. the bindings changed (wrangler.jsonc, vars, Durable Objects, the Worker entry):
 *      the committed CloudflareEnv no longer matches what the Worker receives. That is
 *      a real error, and it still fails here.
 *   2. only the installed workerd changed: the file's header says
 *      "Runtime types generated with workerd@<old version>". Every Wrangler bump
 *      (each weekly Dependabot group update) does this, so every one of those pull
 *      requests failed CI although nothing about the bindings had changed, and no
 *      Dependabot PR could ever pass without a person regenerating the file.
 *
 * Case 2 is reported as a warning (a GitHub annotation in CI) and does not fail
 * the build. `npm run cf-typegen` refreshes the runtime types whenever convenient.
 */
const { spawnSync } = require("node:child_process");
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const COMMITTED = path.join(ROOT, "worker-configuration.d.ts");
// Generated beside the committed file so relative imports ("./worker") come out identical.
const FRESH = path.join(ROOT, ".worker-configuration.check.d.ts");
const ARGS = [
  "--env-interface",
  "CloudflareEnv",
  "--env-file",
  "scripts/wrangler-types.env",
];
const ENV_HEADER = "// Generated by Wrangler by running";
const RUNTIME_HEADER = "// Runtime types generated with";
const RUNTIME_MARKER = "// Begin runtime types";

function wrangler(args) {
  // The package's "exports" hide bin/, so locate it from package.json (works through npm's symlinks too).
  const pkg = require.resolve("wrangler/package.json", { paths: [ROOT] });
  const bin = path.join(path.dirname(pkg), "bin", "wrangler.js");
  return spawnSync(process.execPath, [bin, "types", ...args], {
    cwd: ROOT,
    encoding: "utf8",
  });
}

/** The binding part of a types file: the env hash plus everything before the runtime types. */
function bindingPart(text) {
  const lines = text.replace(/\r\n/g, "\n").split("\n");
  const hash = (lines.find((line) => line.startsWith(ENV_HEADER)) ?? "").match(
    /\(hash: ([a-zA-Z0-9]+)\)/,
  )?.[1];
  const end = lines.indexOf(RUNTIME_MARKER);
  const body = lines
    .slice(0, end === -1 ? lines.length : end)
    .filter(
      (line) =>
        !line.startsWith(ENV_HEADER) && !line.startsWith(RUNTIME_HEADER),
    )
    .join("\n");
  return { hash, body };
}

function runtimeHeader(text) {
  return text
    .replace(/\r\n/g, "\n")
    .split("\n")
    .find((line) => line.startsWith(RUNTIME_HEADER));
}

function main() {
  const check = wrangler(["--check", ...ARGS]);
  if (check.status === 0) {
    process.stdout.write(check.stdout);
    return 0;
  }

  // Out of date: find out whether the bindings or only the runtime types moved.
  try {
    const generated = wrangler([path.basename(FRESH), ...ARGS]);
    if (generated.status !== 0 || !fs.existsSync(FRESH)) {
      process.stderr.write(
        check.stdout + check.stderr + generated.stdout + generated.stderr,
      );
      console.error(
        "Could not regenerate the Cloudflare types to compare them.",
      );
      return 1;
    }
    const committedText = fs.readFileSync(COMMITTED, "utf8");
    const freshText = fs.readFileSync(FRESH, "utf8");
    const committed = bindingPart(committedText);
    const fresh = bindingPart(freshText);
    if (
      !committed.hash ||
      committed.hash !== fresh.hash ||
      committed.body !== fresh.body
    ) {
      console.error(
        "Cloudflare binding types are out of date: worker-configuration.d.ts no longer matches the Worker's bindings.\n" +
          "Run `npm run cf-typegen` and commit the result.",
      );
      return 1;
    }
    const was = runtimeHeader(committedText) ?? "(none)";
    const now = runtimeHeader(freshText) ?? "(none)";
    const message =
      "Cloudflare binding types are current. Only the runtime types are older than the installed workerd " +
      `(${was.replace(RUNTIME_HEADER, "").trim()} -> ${now.replace(RUNTIME_HEADER, "").trim()}); ` +
      "run `npm run cf-typegen` to refresh them.";
    console.log(
      process.env.GITHUB_ACTIONS
        ? `::warning title=Cloudflare runtime types::${message}`
        : message,
    );
    return 0;
  } finally {
    fs.rmSync(FRESH, { force: true });
  }
}

process.exitCode = main();
