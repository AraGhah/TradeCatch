import { readJsonBounded } from "@/lib/request-body";
import { NextRequest, NextResponse } from "next/server";
import { enforcePolicy } from "@/lib/rate-limit-response";
import { z } from "zod";
import { voiceCapabilitiesForPlan } from "@/product/receptionist/plan-limits";
import { defaultProfileSettings } from "@/product/receptionist/profile";
import { getReceptionistRuntime } from "@/product/receptionist/runtime";
import {
  LEGACY_SCENARIOS,
  LIVE_TEST_SCENARIOS,
  LiveTestError,
  runSimulatedPhoneScenario,
  type LiveTestScenario,
} from "@/product/telephony/live-test";
import { buildLiveTestInstructions } from "@/product/telephony/live-test-instructions";
import {
  listSimulations,
  loadSimulation,
  saveSimulation,
  SIMULATION_CALL_PREFIX,
  SimulationPersistenceError,
} from "@/product/telephony/live-test-store";
import { getTelephonyRuntime } from "@/product/telephony/runtime";
import {
  authorizeBusinessMemberOrAdmin,
  loadClientForOrg,
} from "../../_shared";

export const dynamic = "force-dynamic";

type Params = { params: Promise<{ id: string }> };

const scenarioSchema = z
  .enum([
    ...LIVE_TEST_SCENARIOS,
    ...(Object.keys(LEGACY_SCENARIOS) as [string]),
  ])
  .transform(
    (value): LiveTestScenario =>
      (LEGACY_SCENARIOS[value] ?? value) as LiveTestScenario,
  );

const bodySchema = z.object({
  /**
   * `simulation` runs the receptionist engine in memory. `live_instructions`
   * only describes how to call the real number: neither mode ever places a call.
   */
  mode: z.enum(["simulation", "live_instructions"]).default("simulation"),
  scenario: scenarioSchema.default("receptionist_response"),
  language: z.enum(["fr", "en"]).optional(),
  /** Generated by the page per click; repeating a request with it returns the saved run. */
  runId: z.string().uuid().optional(),
});

function problem(
  status: number,
  code: string,
  error: string,
  extra: Record<string, unknown> = {},
) {
  return NextResponse.json({ ok: false, code, error, ...extra }, { status });
}

function fromLiveTestError(error: LiveTestError) {
  return problem(
    error.code === "invalid_configuration" ? 422 : 409,
    error.code,
    error.message,
    error.details ? { details: error.details } : {},
  );
}

async function context(request: NextRequest, id: string) {
  const access = await authorizeBusinessMemberOrAdmin(request, id);
  if (!access.ok) return { response: access.response } as const;
  const client = await loadClientForOrg(access.organization);
  if (!client) {
    return {
      response: problem(
        409,
        "phone_client_not_linked",
        "Phone client is not linked.",
      ),
    } as const;
  }
  return { access, client } as const;
}

/** The business's saved simulations, newest first. Survives refresh and re-login. */
export async function GET(request: NextRequest, { params }: Params) {
  const { id } = await params;
  const ctx = await context(request, id);
  if ("response" in ctx) return ctx.response;

  const runtime = getReceptionistRuntime();
  const scope = { organizationId: id, clientAccountId: ctx.client.id };
  const stores = {
    events: getTelephonyRuntime().events,
    sessions: runtime.store,
  };
  try {
    const callSid = request.nextUrl.searchParams.get("callSid")?.trim();
    if (callSid) {
      if (!callSid.startsWith(SIMULATION_CALL_PREFIX) || callSid.length > 80) {
        return problem(400, "invalid_call_id", "Invalid call id.");
      }
      const loaded = await loadSimulation(scope, stores, callSid);
      if (!loaded) return problem(404, "not_found", "Not found.");
      if (!loaded.complete) {
        return problem(
          409,
          "simulation_incomplete",
          "This simulation did not finish saving.",
        );
      }
      return NextResponse.json({ ok: true, run: loaded.run });
    }
    return NextResponse.json({
      ok: true,
      runs: await listSimulations(scope, stores),
    });
  } catch {
    return problem(
      503,
      "history_unavailable",
      "Saved simulations could not be loaded. Try again in a moment.",
    );
  }
}

export async function POST(request: NextRequest, { params }: Params) {
  const { id } = await params;
  const ctx = await context(request, id);
  if ("response" in ctx) return ctx.response;
  const { access, client } = ctx;
  const limited = await enforcePolicy("tools.call-test", {
    subject: `${id}:${access.ctx?.user.id ?? "ops"}`,
  });
  if (limited) return limited;

  let json: unknown;
  try {
    json = await readJsonBounded(request);
  } catch {
    return problem(400, "invalid_json", "Invalid JSON.");
  }
  const parsed = bodySchema.safeParse(json);
  if (!parsed.success) return problem(400, "invalid_body", "Invalid body.");

  const runtime = getReceptionistRuntime();
  const profile = (await runtime.profileStore.getProfile(id)) ?? {
    organizationId: id,
    activated: false,
    settings: defaultProfileSettings(),
    updatedAt: new Date().toISOString(),
  };
  const capabilities = voiceCapabilitiesForPlan(access.organization.plan);

  if (parsed.data.mode === "live_instructions") {
    // Read-only: no call is placed, nothing is written.
    try {
      await runtime.refresh();
    } catch {
      return problem(
        503,
        "runtime_unavailable",
        "The receptionist settings could not be loaded. Try again in a moment.",
      );
    }
    return NextResponse.json({
      ok: true,
      ...buildLiveTestInstructions({
        organizationId: id,
        profile,
        client,
        capabilities,
        configs: runtime.configs,
      }),
    });
  }

  const scope = { organizationId: id, clientAccountId: client.id };
  const stores = {
    events: getTelephonyRuntime().events,
    sessions: runtime.store,
  };

  try {
    // The same click sent twice (a retry after a dropped response) is one run.
    if (parsed.data.runId) {
      const existing = await loadSimulation(
        scope,
        stores,
        `${SIMULATION_CALL_PREFIX}${parsed.data.runId}`,
      );
      if (existing?.complete) {
        return NextResponse.json({
          ok: true,
          mode: "simulation",
          replayed: true,
          run: existing.run,
        });
      }
      if (existing) {
        return problem(
          409,
          "simulation_incomplete",
          "An earlier attempt did not finish saving. Run the simulation again.",
        );
      }
    }

    const output = await runSimulatedPhoneScenario({
      organizationId: id,
      profile,
      client,
      scenario: parsed.data.scenario,
      language: parsed.data.language,
      capabilities,
      runId: parsed.data.runId,
    });
    await saveSimulation(output, scope, stores);
    return NextResponse.json({ ok: true, mode: "simulation", run: output.run });
  } catch (error) {
    if (error instanceof LiveTestError) return fromLiveTestError(error);
    if (error instanceof SimulationPersistenceError) {
      return problem(
        503,
        "persistence_failed",
        "The simulation ran but its result could not be saved, so it is not shown. Try again in a moment.",
        { stage: error.stage },
      );
    }
    console.error(
      JSON.stringify({
        event: "tradecatch.live_test.failed",
        code: error instanceof Error ? error.name : "Error",
      }),
    );
    return problem(
      500,
      "simulation_failed",
      "The simulation failed unexpectedly. Nothing was called.",
    );
  }
}
